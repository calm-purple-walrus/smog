"""Hand-written text for every metric and check, as data. Each entry describes what the code computes.

`title` is the one-line description, `measures` what the code computes, `improve` an action to take, and `gaming` a
known exploit from section 3.12 of the design or the research behind it. `heuristic` marks a metric the registry calls
computed while the code matches names or text. `policy` replaces the generated policy call where a check needs settings.
A name in braces, such as `{short_term_window}`, is a setting from `smog.domain.settings`; `--explain` prints its value in force.
"""

def _unreviewed(where: str, share_of: str = "") -> dict:
    """The entry of a count of unreviewed lines, or with `share_of`, the ID of a share, of that share."""
    divided = ", divided by the code lines there," if share_of else ""
    return {
        "title": "share of lines no human reviewed" if share_of else "lines no human reviewed",
        "measures": (
            f"Code lines in {where} that no human reviewed{divided} where a line is reviewed when the commit that last changed it "
            "(`git blame --first-parent`) is a commit or the merge or squash commit of a merged pull request that a login from "
            "`policy.humans` approved (their latest review is an approval) or merged, or a commit such a login made without a pull request, "
            "or when one of the first {human_review_marker_lines} lines of its file is a comment that holds `{human_review_marker}` and the "
            "hash of a commit, and nothing else, and the line last changed in that commit or an earlier one. Every other code line is "
            "unreviewed, a line not committed yet included."
        ),
        "improve": (
            "Have a listed human approve the pull request before it is merged, or put the marker comment at the top of a file "
            "reviewed outside GitHub. A request for changes or a dismissal after the approval takes the sign-off away."
        ),
        "gaming": (
            "An approval does not show how closely the human read the change, and the marker comment is checked against no review. "
            "A review in a state of {review_ignored_states} leaves an earlier review standing, and an approval given before later "
            "commits of the pull request still counts."
        ),
        "policy": 'policy.humans("github-login")' + (f'; policy.select("{share_of}", target=..., limit=..., group="review")' if share_of else ""),
    }


