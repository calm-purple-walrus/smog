def rule_setting(rule_id: str) -> str:
    """The name of the setting that holds the parameters of a rule, such as `slop_rule_neg_not_only`."""
    return "slop_rule_" + rule_id.replace("-", "_")


def list_setting(name: str) -> str:
    """The name of the setting that holds a word list, such as `slop_list_vocab_weak`."""
    return "slop_list_" + name


def macro_words(name: str) -> tuple[str, ...]:
    """The alternatives of a macro: `MACROS` writes them as `(?:a|b|c)`."""
    return tuple(MACROS[name].removeprefix("(?:").removesuffix(")").split("|"))


def rule_parameters(rule_id: str) -> dict:
    """What a policy can change about one rule.

    `severity` for every rule; `limit_severity` for a rule of `LIMIT_RULES`; `patterns` and `exceptions`, with
    their quantifiers, for a rule that matches regular expressions; `comments_only` for a rule the pattern
    runner applies to blocks of prose and for `comment-ticket`. A rule has only the parameters its code reads:
    one that matches the raw text of a file, such as `art-citation`, cannot tell a comment from other text and
    has no `comments_only`. `class`, `kind`, `scope`, `strip` and `source` are not parameters: they say which
    code runs the rule and on which form of the text.
    """
    rule = RULES[rule_id]
    parameters: dict = {"severity": rule["severity"]}
    if rule_id in LIMIT_RULES:
        parameters["limit_severity"] = "warn"
    if rule["patterns"]:
        parameters["patterns"] = tuple(rule["patterns"])
        parameters["exceptions"] = tuple(rule.get("except", ()))
    if (rule["kind"] == "pattern" and rule["scope"] != "F") or "comments_only" in rule:
        parameters["comments_only"] = bool(rule.get("comments_only"))
    return parameters


def settings_rows() -> dict[str, tuple]:
    """A settings row (default, description, affected IDs) per rule, per word list, per macro and for the homonyms."""
    rows: dict[str, tuple] = {}
    for rule_id in RULES:
        parameters = rule_parameters(rule_id)
        parts = ["its severity (`block`, `warn` or `metric`)"]
        if "limit_severity" in parameters:
            parts.append("the severity at its limit")
        if "patterns" in parameters:
            parts.append("its regular expressions with their quantifiers, and the expressions that except the matches they overlap")
        if "comments_only" in parameters:
            parts.append("whether it reads comments only")
        rows[rule_setting(rule_id)] = (
            parameters,
            f"The parameters of the slop rule {rule_id}: {', '.join(parts)}. Give the keys to change.",
            (rule_id, *_MATCH_READERS.get(rule_id, ())),
        )
    for name, entries in LISTS.items():
        users = [rule_id for rule_id, rule in RULES.items() if any("{list:" + name + "}" in pattern for pattern in rule["patterns"])]
        description = f"The word list `{name}`: {_LIST_USES[name]}. Each entry is a regular expression, a replacement to suggest and a source."
        rows[list_setting(name)] = (tuple(tuple(entry) for entry in entries), description, (*users, *_LIST_READERS.get(name, ())))
    for name, setting, description in (
        ("N", "slop_number_words", "The words for the numbers from 2 upward, in order, where a rule looks for a count written as a word. Each is matched as it is written."),
        ("ABS", "slop_abstract_nouns", "The nouns, as regular expressions, that a count or a range is announced with."),
    ):
        users = [rule_id for rule_id, rule in RULES.items() if any("{" + name + "}" in pattern for pattern in rule["patterns"])]
        rows[setting] = (macro_words(name), description, (*users, *(("count-mismatch",) if name == "N" else ())))
    rows["slop_homonyms"] = (
        tuple(HOMONYMS),
        "Words with a plain and a mannered use: a name, the regular expression of the mannered use, and one that excepts a sentence.",
        ("vocab-context",),
    )
    return rows
